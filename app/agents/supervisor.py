from app.errors import classify_error
from app.logging_config import logger
from app.models import get_model
from app.schemas import AgentState, DecisionSupervisor

MAX_STEPS = 6

SUPERVISOR_PROMPT = """You are the Supervisor of a team consisting of two specialists:

- agent_teacher: answers the user's conceptual questions and, if requested,
  can provide the sources used.
- agent_evaluator: evaluates whether the concept explained by the user is correct and,
  when appropriate, indicates what information the user should study and where to find it
  in the retrieved sources.

RULES:

1. If the user asks a conceptual question, use "teacher".

2. If the user provides their own answer and requests or requires
   an assessment of their knowledge, use "evaluator".

3. If "teacher" has already provided a sufficient answer to a conceptual question,
   select "FINISH". Do not send that answer to "evaluator".

4. If "evaluator" has already assessed the user's answer, select "FINISH".

5. Do not use "evaluador" to assess the answer generated by "teacher".

6. If the task has already been completed by the appropriate specialist,
   select "FINISH".

7. Before selecting "FINISH", verify that the specialist's contribution
   is sufficient to address the original request. If relevant information is missing,
   select the appropriate specialist.

8. Do not unnecessarily invoke the same agent again if it has already fulfilled its role.

Contributions so far:
{contributions}
"""

async def node_supervisor(state: AgentState) -> dict:

    if state.get("steps", 0) >= MAX_STEPS:
        return {
            "next_agent": "FINISH",
            "task_completed": True,
        }

    text_contributions = "\n".join(
        f"- {c['agent']}: {c['contribution'][:500]}"
        for c in state.get("contributions", [])
    ) or "(any yet)"

    actual_question = state["messages"][-1].content

    system_prompt = SUPERVISOR_PROMPT.format(
        contributions=text_contributions
    )

    messages = [
        {
            "role": "system",
            "content": system_prompt,
        },
        {
            "role": "user",
            "content": f"Actual task: {actual_question}",
        },
    ]

    last_error = None

    for provider in ["openai", "anthropic", "gemini"]:
        try:
            logger.info(
                "Trying to initialize an LLM provider for the supervisor: %s",
                provider,
            )

            llm = get_model(provider)

            llm_supervisor = llm.with_structured_output(
                DecisionSupervisor
            )

            decision = await llm_supervisor.ainvoke(messages)

            logger.info(
                "LLM provider successfully executed: %s",
                provider,
            )

            return {
                "next_agent": decision.next,
                "task_completed": decision.next == "FINISH",
            }

        except Exception as e:
            last_error = e

            error = classify_error(e)

            logger.warning(
                "The provider %s failed: %s",
                provider,
                error.message,
            )

            continue

    logger.error("All LLM providers failed")

    raise classify_error(last_error)